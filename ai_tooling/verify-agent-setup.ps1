# Checks the agent setup: the skills against ai_tooling/manifest/skills.json (folders,
# frontmatter, limits, naming), the subagent definitions, PERMISSIONS.md and the
# instruction stubs, every MCP server, and what setup.ps1 published for Claude
# Code, Antigravity, Copilot and Cursor; then the project's own checks
# (ai_tooling/scripts/verify-project.ps1).
#
#   .\ai_tooling\verify-agent-setup.ps1               everything
#   .\ai_tooling\verify-agent-setup.ps1 -SourceOnly   only the committed source, as a PR
#                                                     build runs it: no published layouts,
#                                                     tools, network or git visibility
#   .\ai_tooling\verify-agent-setup.ps1 -Quick        only whether what setup.ps1 copied
#                                                     still matches its sources, the skill
#                                                     junctions, and personal MCP servers
#                                                     that hide a project one; run by the
#                                                     session-start check in AGENTS.md
#
# Run after an IDE, extension, or SDK update, or whenever something misbehaves.
#
# The shared source is ai_tooling/ and it is COMMITTED. Every per-agent layout is
# GENERATED by ai_tooling/setup.ps1 and gitignored. The "Git visibility" section at
# the end enforces that boundary in both directions. Where each agent's layout is
# comes from ai_tooling/manifest/agents.json, the same as for setup.ps1.

param(
