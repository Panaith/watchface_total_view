# A generated config only stays correct while setup.ps1 keeps regenerating it.
# "Present" is not the same as "current", so compare the contents: a wrong
# config is worse than a missing one.
foreach ($lf in @(if ($SourceOnly -or -not $serversOk) { @() } else { $Layouts.Values })) {
    $n = $lf.Name
    if (-not (Test-Path $lf.Mcp)) { continue }
    $expected = @($serverNames | Where-Object { -not ($Servers.$_.skipAgents -contains $lf.Key) })
    $gen = $null
    $mcpText = ''
    try { $mcpText = [System.IO.File]::ReadAllText($lf.Mcp); $gen = ($mcpText | ConvertFrom-Json).($lf.McpKey) } catch { }
    $actual = @()
    if ($gen) { $actual = @($gen.PSObject.Properties.Name) }
    $missing = @($expected | Where-Object { $actual -notcontains $_ })
    $fix = if ($lf.McpInHome -and (Test-JsonComment $mcpText)) { 'the file has comments, which setup.ps1 leaves alone: remove them, then re-run setup.ps1' } else { 're-run setup.ps1' }
    Check "$n MCP lists every server" ($missing.Count -eq 0) "missing $($missing -join ', ') - $fix"
    # Transport drift: an entry can survive a change of shape (http -> stdio) and
    # still look present while pointing somewhere that no longer works.
    $drift = @()
    foreach ($sv in $expected) {
        if (-not $gen.$sv) { continue }
        $wantStdio = ($Servers.$sv.transport -ne 'http')
        if ([bool]$gen.$sv.command -ne $wantStdio) { $drift += $sv }
    }
    Check "$n MCP transports match the source" ($drift.Count -eq 0) "$($drift -join ', ') has the wrong shape - re-run setup.ps1"
}

