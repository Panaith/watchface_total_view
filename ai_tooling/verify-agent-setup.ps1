    if ($usesNode) {
        $nodeV = if (Get-Command node -ErrorAction SilentlyContinue) { (node --version) -replace '[^0-9.]','' } else { $null }
        if ($nodeV -and ([int](($nodeV -split '\.')[0]) -ge 20)) { Write-Host "  OK    node $nodeV" }
        else { Write-Host "  WARN  node 20+ not found - the node-based MCP servers cannot start" }
    }
    foreach ($cmd in @($serverNames | ForEach-Object { $Servers.$_.command } | Where-Object { $_ -and $_ -ne 'node' } | Select-Object -Unique)) {
        if (Get-Command $cmd -ErrorAction SilentlyContinue) { Write-Host "  OK    $cmd on PATH" }
        else { Write-Host "  WARN  $cmd not on PATH - the servers it starts cannot run" }
    }
    # Without its pinned copy, npm-mcp.js falls back to npx, which still works but
