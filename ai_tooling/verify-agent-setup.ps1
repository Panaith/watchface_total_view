        Check "$n : $rel present" (Test-Path (Join-Path $RepoRoot $rel)) "the server cannot start; restore the file or fix args in mcp-servers.json"
    }
    foreach ($skipped in @($Servers.$n.skipAgents)) {
        if ($skipped) { Check "$n : skipAgents '$skipped' is an agent in agents.json" ($Layouts.Contains($skipped)) "fix skipAgents" }
