function Check($label, $ok, $detail) {
    if ($ok) { Write-Host "  OK    $label" }
    else     { Write-Host "  FAIL  $label" -ForegroundColor Red; if ($detail) { Write-Host "        $detail" }; $script:fail++ }
}

# The first few names of a list, and how many more.
function Format-ShortList([string[]]$names, [int]$max = 5) {
    $shown = ($names | Select-Object -First $max) -join ', '
    if ($names.Count -gt $max) { $shown += ", ... ($($names.Count - $max) more)" }
    return $shown
}

# What a copy-based agent reads goes stale when its source changes (an edit, a
# pull, a branch switch) until setup runs again; the version check does not see
# that. Compares the hashes setup.ps1 recorded in localsources.json with the
# working tree, checks that every skill junction of the profile is there, and
# warns about a personal MCP server that wins over the project one of that name.
function Test-CopiesCurrent {
    Write-Host "Copies and junctions ($Tooling/$LocalSourcesName against the working tree)"
    $manifest = Read-SkillManifest $AiDir
    $profileNames = Read-LocalProfile $RepoRoot
    try { $names = @(Resolve-SkillProfile $manifest $profileNames) }
    catch { Check "profile '$($profileNames -join ',')' in $Tooling/localprofile exists" $false "$($_.Exception.Message) - re-run $Tooling/setup.ps1 -Profile ..."; return }
    $sources = Get-SetupSources $AiDir $RepoRoot $env:USERPROFILE $manifest $names
    $results = @(Test-LocalSources $RepoRoot $Layouts $sources)
    foreach ($r in $results) {
        if (-not $r.Recorded) {
            Check "$($r.Name) : copies recorded" $false "no record in $Tooling/$LocalSourcesName - re-run $Tooling/setup.ps1"
            continue
        }
        $diff = @($r.Changed | ForEach-Object { "$_ (changed)" }) + @($r.Added | ForEach-Object { "$_ (new)" }) + @($r.Removed | ForEach-Object { "$_ (gone)" })
        Check "$($r.Name) : copies match their sources ($($r.Count))" ($diff.Count -eq 0) "$(Format-ShortList $diff) - re-run $Tooling/setup.ps1"
        $l = $Layouts[$r.Key]
        if ($l.SkillLinks -eq 'junction') {
            $pub = Test-PublishedSkills $l $sources.Skills $sources.SkillsDir $sources.AllSkillNames
            $broken = @($pub.Missing) + @($pub.Dangling)
            Check "$($r.Name) : skill junctions of profile '$($profileNames -join ',')' present ($($sources.Skills.Count))" ($broken.Count -eq 0) "$(Format-ShortList $broken) missing or dangling - re-run $Tooling/setup.ps1"
        }
    }
    if (-not $results) { Write-Host "  SKIP  no agent configured yet - run $Tooling/setup.ps1" }
    foreach ($l in @($Layouts.Values | Where-Object { Test-LayoutOnDisk $_ })) { Test-McpKeepValid $l }
    $mcp = Get-McpNameInfo $sources.Servers
    $hiding = @(Get-ShadowingEntries $Layouts $env:USERPROFILE $env:APPDATA $RepoRoot $manifest $mcp.Names $mcp.Skip | Where-Object { ($_.Kind -eq 'mcp') -and $_.Hides })
    foreach ($e in $hiding) {
        Write-Host "  WARN  $($e.Location) ($($e.Name)): $($e.Agent) uses this server instead of the project one - rename or remove it"
    }
}

# Each file of the layout's mcp.keepValid must hold a JSON object: while
# Antigravity's global file is empty it loads no MCP server at all (seen with
# Antigravity 2.24.0). setup.ps1 fills a missing or blank one; a file with
# something else in it needs a hand fix. A file with comments passes:
# Antigravity writes JSONC.
function Test-McpKeepValid($Layout) {
    foreach ($f in @($Layout.McpKeepValid)) {
        $text = if (Test-Path -LiteralPath $f -PathType Leaf) { [System.IO.File]::ReadAllText($f) } else { '' }
        $hint = $null
        if (-not $text.Trim()) {
            $hint = "missing or empty, so $($Layout.Name) loads no MCP server, not even the workspace file's - re-run $Tooling/setup.ps1"
        } elseif (-not (Test-JsonComment $text)) {
            $object = $false
            try { $object = ($text | ConvertFrom-Json) -is [System.Management.Automation.PSCustomObject] } catch { }
            if (-not $object) { $hint = 'not a JSON object - fix it by hand, for example { "mcpServers": { your own servers } }' }
        }
        Check "$($Layout.Name) : $($f.Replace($env:USERPROFILE, '~')) holds a JSON object" (-not $hint) $hint
    }
}

# The project's MCP server names (mcp-servers.json) and, per name, the agent
# keys it is not written for (skipAgents), for Get-ShadowingEntries.
function Get-McpNameInfo($Servers) {
    $names = @(if ($Servers) { $Servers.PSObject.Properties | ForEach-Object { $_.Name } | Where-Object { $_ -ne '$comment' } })
    $skip = @{}
    foreach ($n in $names) { if ($Servers.$n.skipAgents) { $skip[$n] = @($Servers.$n.skipAgents) } }
    return @{ Names = $names; Skip = $skip }
}

